import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { mkdir } from 'node:fs/promises';
import { join } from 'node:path';
const artifactDir = join(process.cwd(), '.tmp');
await mkdir(artifactDir, { recursive: true });
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:5173/#/briefing/1');
  await page.getByRole('heading', { name: 'Where did the answer get its evidence?' }).waitFor();
  await page.getByRole('button', { name: 'Skip to step explanation' }).click();
  assert.equal(new URL(page.url()).hash, '#/briefing/1');
  await page.getByRole('link', { name: /Assemble the evidence/ }).click();
  await page.getByRole('radio', { name: /Unverified from this context/ }).check();
  await page.getByRole('button', { name: 'Remove notice' }).click();
  assert.match(await page.getByRole('img').getAttribute('aria-label'), /unverified.*not booked/i);
  await page.getByRole('button', { name: /Inspect exact evidence/ }).click();
  assert.match(await page.getByRole('dialog').innerText(), /CURRENT RECORD · NOT IN ANSWER CONTEXT/);
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({ state: 'detached' });
  await page.screenshot({ path: join(artifactDir, 'briefing-player-desktop.png'), fullPage: true });
  await page.goto('http://127.0.0.1:5173/#/briefing-classic');
  await page.getByRole('heading', { name: 'The briefing' }).waitFor();
  await page.getByRole('button', { name: 'Hide 3D view' }).waitFor();
  await page.locator('canvas, .scene-fallback').first().waitFor();
  assert.match(await page.locator('.lesson-grid').innerText(), /Evidence trail/);
  await page.getByRole('button', { name: 'Motion: standard' }).click();
  assert.match(await page.locator('.scene-controls').innerText(), /static scene/);
  await page.getByRole('button', { name: 'Hide 3D view' }).click();
  await page.getByRole('radio', { name: /Availability is unverified/ }).check();
  await page.getByRole('button', { name: /Reveal the change/ }).click();
  await page.getByText('The status becomes unverified.').waitFor();
  assert.match(await page.locator('.comparison').innerText(), /Saturday application-help availability cannot be verified/);
  await page.getByRole('link', { name: /The library/ }).click();
  await page.getByRole('radio', { name: /No, the notice is not/ }).check();
  await page.getByRole('button', { name: /Reveal the change/ }).click();
  assert.match(await page.locator('.lesson-side').innerText(), /cannot add a missing document/i);
  await page.getByRole('link', { name: /The service counter/ }).click();
  await page.getByRole('radio', { name: /Availability is unknown/ }).check();
  await page.getByRole('button', { name: /Reveal the change/ }).click();
  assert.match(await page.locator('.comparison').innerText(), /Not booked/);
  await page.reload();
  assert.match(await page.locator('.comparison').innerText(), /calendar did not respond/i);
  await page.goto('http://127.0.0.1:5173/#/briefing-classic');
  assert.match(await page.locator('.comparison').innerText(), /cannot be verified/i);
  await page.getByRole('button', { name: 'Step 0' }).click();
  assert.match(await page.locator('.lesson-side').innerText(), /Current notice reaches/);
  await page.getByRole('button', { name: /Reset this room/ }).click();
  assert.match(await page.locator('.comparison').innerText(), /suspended/i);
  assert.deepEqual(errors, []);
  await page.screenshot({ path: join(artifactDir, 'phase2-desktop.png'), fullPage: true });
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 });
  await mobile.goto('http://127.0.0.1:5173/#/briefing/4');
  await mobile.getByRole('heading', { name: 'Where did the answer get its evidence?' }).waitFor();
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await mobile.screenshot({ path: join(artifactDir, 'briefing-player-mobile.png'), fullPage: true });
  await mobile.goto('http://127.0.0.1:5173/#/library');
  await mobile.getByRole('heading', { name: 'The library' }).waitFor();
  await mobile.getByRole('button', { name: 'Hide 3D view' }).waitFor();
  await mobile.locator('canvas, .scene-fallback').first().waitFor();
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await mobile.screenshot({ path: join(artifactDir, 'phase2-mobile.png'), fullPage: true });
  console.log('Browser smoke passed: three routes, guided changes, persistence, replay, reset, mobile width, no runtime errors.');
} finally { await browser.close(); }
